from __future__ import annotations

import argparse
import json
import math
import pathlib

from omegaconf import OmegaConf

from isaac_sim.scenes._common import (
    WAREHOUSE_2X3_ZONES,
    WAREHOUSE_2X3_NAV_X,
)
from isaac_sim.planning.a_star.offline_gate import has_path, path_length, path_points
from isaac_sim.run_builders.build_2x3 import DataGenerator, BASE_USDA

_THIS = pathlib.Path(__file__).resolve().parent          # run_builders/
_NSC = _THIS.parent                                      # -> isaac_sim/
SCENE_DIR = _NSC / "configs" / "env" / "scene"
EXP_DIR = _NSC / "configs" / "experiment"
GRID_CFG = _NSC / "configs" / "eval_grid72_2x3.yaml"
DATAGEN_CFG = _NSC / "configs" / "datagen_2x3.yaml"
VIZ_DIR = _NSC / "outputs" / "grid72"

# top-down map view, north up: L = west, C = centre, R = east
POSITIONS = ("L", "C", "R")


def grid_xs(edge_margin_m: float) -> dict:
    x_lo, x_hi = WAREHOUSE_2X3_NAV_X
    return {
        "L": round(x_lo + edge_margin_m, 3),
        "C": round((x_lo + x_hi) / 2.0, 3),
        "R": round(x_hi - edge_margin_m, 3),
    }


def make_blocker(zone: str) -> dict:
    """Forklift sealing `zone`: aisle-centre x, row-centre y, turned across the
    aisle — the placement already validated by the probe_* runway scenes."""
    z = WAREHOUSE_2X3_ZONES[zone]
    return {"kind": "forklift", "variant": 0,
            "x": round(z.center[0], 3), "y": round(z.center[1], 3),
            "yaw_deg": 90.0, "role": "blocker"}


def build_grid(grid_cfg, gen: DataGenerator) -> list:
    """Returns the 72 (scene, meta) pairs, gate-verified. Raises if any
    forklift fails to seal its aisle or any scene becomes unsolvable."""
    xs = grid_xs(float(grid_cfg.edge_margin_m))
    spawn_y = float(grid_cfg.spawn_y)
    goal_y = round(WAREHOUSE_2X3_ZONES["G"].center[1], 3)
    sg_clear = float(gen.cfg.placement.start_goal_clearance_m)

    out = []
    for s_pos in POSITIONS:
        for g_pos in POSITIONS:
            start_xy = (xs[s_pos], spawn_y)
            goal_xy = (xs[g_pos], goal_y)
            len_empty = path_length(gen.static_rects, start_xy, goal_xy, gen.gate_cfg)
            assert len_empty, f"no empty-map path for s{s_pos}->g{g_pos}"
            for cond in list(grid_cfg.conditions):
                zones = list(str(cond))
                blockers = []
                for z in zones:
                    b = make_blocker(z)
                    assert gen._seals_aisle(z, b), f"forklift fails to seal aisle {z}"
                    blockers.append(b)
                rects = [gen._obstacle_rect(b) for b in blockers]
                assert has_path(gen.static_rects + rects, start_xy, goal_xy,
                                gen.gate_cfg), \
                    f"s{s_pos}->g{g_pos} cf{cond}: goal unreachable"
                len_blocked = path_length(gen.static_rects + rects, start_xy,
                                          goal_xy, gen.gate_cfg)
                pts = path_points(gen.static_rects + rects, start_xy, goal_xy,
                                  gen.gate_cfg)
                route = sorted(gen._aisles_on_points(pts))
                assert not set(route) & set(zones), \
                    f"s{s_pos}->g{g_pos} cf{cond}: route threads a sealed aisle"
                name = f"warehouse_2x3_grid_s{s_pos}_g{g_pos}_cf{cond}"
                scene = {
                    "template": "warehouse_2x3", "name": name,
                    "base_usda": BASE_USDA,
                    "seed": int(grid_cfg.seed),
                    "start_xy": list(start_xy),
                    "start_heading_deg": float(grid_cfg.start_heading_deg),
                    "start_heading_mode": "fixed",
                    "goal_xy": list(goal_xy),
                    "goal_kinds": [], "goal_yaw_deg": 0.0,
                    "goal_clear_radius": sg_clear,
                    "lighting": str(grid_cfg.lighting),
                    "obstacles": blockers,
                }
                meta = {
                    "name": name, "spawn": s_pos, "goal": g_pos,
                    "condition": str(cond), "blocked_zones": zones,
                    "start_xy": list(start_xy), "goal_xy": list(goal_xy),
                    "route_aisles": route,
                    "path_len_empty_m": round(len_empty, 2),
                    "path_len_blocked_m": round(len_blocked, 2) if len_blocked else None,
                    "elongation": (round(len_blocked / len_empty, 3)
                                   if len_blocked else None),
                }
                out.append((scene, meta))
    return out


def _write_scene(scene: dict) -> str:
    name = scene["name"]
    (SCENE_DIR / f"{name}.yaml").write_text(
        "# @package env\n# AUTO-GENERATED by build_2x3_grid72.py (systematic "
        "3x3x8 eval grid).\n# DO NOT hand-edit; re-run the generator.\n"
        + json.dumps(scene, indent=2) + "\n")
    return name


